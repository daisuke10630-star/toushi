"""
証券コードから業種ブロックを判定する。

■ なぜこれを使うのか
yfinance の業種情報は551銘柄中241銘柄しか取れず（残りは unknown）、
業種の集中を制限しようとしても機能しなかった。
1銘柄ずつ問い合わせると15〜25分かかるうえ、過負荷時に壊れた応答が返る。

東証の証券コードは業種ごとにブロックが割り当てられているため、
**通信ゼロ・即座に・全銘柄を**分類できる。yfinance の業種より粗いが、
「同じ業種に偏っていないか」を見るには十分で、取りこぼしがない。

■ 限界
コードは上場時に割り当てられるため、事業転換した企業は実態とずれる。
あくまで集中の目安として使い、正確な業種表示には yfinance 側を使う。
"""

# 東証の証券コード割り当て（伝統的なブロック構成）
BLOCKS: list[tuple[int, int, str]] = [
    (1300, 1499, "水産・農林・鉱業"),
    (1500, 1999, "建設"),
    (2000, 2999, "食品"),
    (3000, 3999, "繊維・パルプ紙・化学"),
    (4000, 4999, "化学・医薬品"),
    (5000, 5999, "石油・ゴム・窯業・鉄鋼・非鉄"),
    (6000, 6999, "機械・電気機器"),
    (7000, 7999, "輸送用機器・精密機器"),
    (8000, 8999, "商業・金融・不動産"),
    (9000, 9999, "運輸・情報通信・電力・サービス"),
]


def block_of(code: str) -> str:
    """証券コードから業種ブロック名を返す。判定できなければ "その他"。"""
    try:
        n = int(str(code)[:4])
    except (TypeError, ValueError):
        return "その他"
    for lo, hi, name in BLOCKS:
        if lo <= n <= hi:
            return name
    return "その他"


def block_key(code: str) -> str:
    """集計用の短いキー（例: "6000番台"）。"""
    try:
        n = int(str(code)[:4])
    except (TypeError, ValueError):
        return "other"
    for lo, hi, _ in BLOCKS:
        if lo <= n <= hi:
            return f"{lo}"
    return "other"
