# scripts/build_universe.py が生成する拡張リスト。
# 売買代金でふるいにかけ、ETF・ETNを除いた個別株だけが入っている。
_EXPANDED_PATH = pathlib.Path(__file__).with_name("universe_codes.json")


def _expanded() -> list[str]:
    if not _EXPANDED_PATH.exists():
        return []
    try:
        data = json.loads(_EXPANDED_PATH.read_text(encoding="utf-8"))
        return [str(c) for c in data.get("codes", [])]
    except Exception:
        return []


def info() -> dict:
    """母集団の由来（いつ・どの条件で作ったか）。"""
    if not _EXPANDED_PATH.exists():
        return {"source": "内蔵リスト（日経225中心）", "count": len(codes())}
    try:
        d = json.loads(_EXPANDED_PATH.read_text(encoding="utf-8"))
        return {
            "source": "拡張リスト",
            "built_at": d.get("built_at"),
            "min_turnover": d.get("min_turnover"),
            "count": len(codes()),
        }
    except Exception:
        return {"source": "不明", "count": len(codes())}


def codes() -> list[str]:
    """重複を除いた母集団のコード一覧を返す。

    拡張リストがあればそれを使い、無ければ内蔵の日経225中心リストにフォールバックする。
    保有銘柄（EXTRA）は必ず含める。
    """
    seen: dict[str, None] = {}
    for c in _expanded() or (NIKKEI_CORE + EXPANSION):
        seen.setdefault(c, None)
    for c in EXTRA:
        seen.setdefault(c, None)
    return list(seen)
